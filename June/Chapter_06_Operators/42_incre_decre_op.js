// pre increment
let a = 10;
let b = ++a;//(increment a by 1 )

// pre increment  -> ++a  -> increase the value and assign

console.log("a  :" + a)
console.log("b  :" + b);


// pre-decrement

let m =10;
let n = --m;

console.log(m);
console.log(n);

//post decrement
let h =10;
let d= h--;
console.log(h);
console.log(d);

